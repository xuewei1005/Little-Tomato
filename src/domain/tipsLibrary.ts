export const TIP_LIBRARY: readonly PracticalTip[] = Object.freeze(
  TIP_GROUPS.flatMap(({ category, prefix, texts }) =>
    texts.map((text, index) => Object.freeze({ id: `${prefix}-${index + 1}`, category, text })),
  ),
);

export function chooseTip({ random = Math.random, category, previousTip }: ChooseTipOptions = {}): PracticalTip {
  const pool = category === undefined ? TIP_LIBRARY : TIP_LIBRARY.filter((tip) => tip.category === category);
  const withoutPrevious = pool.filter((tip) => tip.text !== previousTip);
  const candidates = withoutPrevious.length > 0 ? withoutPrevious : pool;
  const sample = random();
  const normalized = Number.isFinite(sample) ? Math.min(1, Math.max(0, sample)) : 0;
  const index = Math.min(candidates.length - 1, Math.floor(normalized * candidates.length));

  return candidates[index] ?? TIP_LIBRARY[0];
}

