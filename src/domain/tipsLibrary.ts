export function localizeTip(tip: string, language: AppLanguage = 'zh-CN'): string {
  return LOCALIZED_TIP_OVERRIDES[language]?.[tip] ?? tip;
}

export function getRandomTip(random: () => number = Math.random, options: TipSelectionOptions = {}): string {
  return chooseTip({ ...options, random }).text;
}

export function getTips(language: AppLanguage = 'zh-CN'): string[] {
  return TIP_LIBRARY.map(({ text }) => localizeTip(text, language));
}
